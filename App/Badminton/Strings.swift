@Observable
final class Strings {
    static let shared = Strings()
    var lang = "en"

    private let tables: [String: [String: String]] = ["zh": zh, "en": en]

    func t(_ key: String, _ args: [String: Any] = [:]) -> String {
        var s = tables[lang]?[key] ?? key
        for (k, v) in args {
            s = s.replacingOccurrences(of: "{\(k)}", with: "\(v)")
        }
        return s
    }
}

func T(_ key: String, _ args: [String: Any] = [:]) -> String {
    Strings.shared.t(key, args)
}
